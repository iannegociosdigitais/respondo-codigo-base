export const RTL_LANGS: FormLang[] = ["he", "ar"];

export function pickFormLang(raw: string | null | undefined): FormLang {
  const l = (raw ?? "").toLowerCase().slice(0, 2);
  return l in FORM_STRINGS ? (l as FormLang) : "en";
}
